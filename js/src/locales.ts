export const LOCALES = { en, fr, pt, es, it, ar, de, pl, nl, cs } as const;

export type Locale = keyof typeof LOCALES;

export const RTL_LOCALES: ReadonlySet<Locale> = new Set(["ar"]);

function supported(tag: string | null | undefined): Locale | undefined {
  const base = (tag ?? "").trim().toLowerCase().split(/[-_]/)[0] ?? "";
  return base in LOCALES ? (base as Locale) : undefined;
}

/** First supported of: the `locale` option, `<html lang>`, the browser languages; else "en". */
export function resolveLocale(locale?: string): Locale {
  const candidates = [
    locale,
    typeof document !== "undefined" ? document.documentElement.lang : undefined,
    ...(typeof navigator !== "undefined" ? (navigator.languages ?? [navigator.language]) : []),
  ];
  for (const candidate of candidates) {
    const found = supported(candidate);
    if (found) return found;
  }
  return "en";
}
